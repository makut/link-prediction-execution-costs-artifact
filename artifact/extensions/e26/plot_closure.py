def sha_hex(value):return isinstance(value,str)and len(value)==64 and set(value)<=set('0123456789abcdef')


def decode(raw):
 def pairs(rows):
  out={}
  for key,value in rows:need(key not in out,'duplicate JSON key');out[key]=value
  return out
 def number(token):
  value=float(token);need(math.isfinite(value),'nonfinite JSON number');return value
 return json.loads(raw,object_pairs_hook=pairs,parse_float=number,
  parse_constant=lambda _:(_ for _ in ()).throw(ValueError('nonfinite JSON')))


def identity(path,maximum=8*MIB):
 path=Path(path);need(path.is_file()and not path.is_symlink()and path.stat().st_size<=maximum,'bounded regular input required')
 before=path.stat();h=hashlib.sha256();n=0
 with path.open('rb')as stream:
  for chunk in iter(lambda:stream.read(MIB),b''):n+=len(chunk);need(n<=maximum,'growing input');h.update(chunk)
 after=path.stat();need((before.st_ino,before.st_size,before.st_mtime_ns)==(after.st_ino,after.st_size,after.st_mtime_ns)
  and n==before.st_size,'input changed while reading')
 return dict(bytes=n,sha256=h.hexdigest())


def read_pinned(path,sha):
 need(sha_hex(sha),'full explicit input SHA256 required');pin=identity(path)
 need(pin['sha256']==sha,'input whole SHA256 differs');raw=Path(path).read_bytes()
 need(len(raw)==pin['bytes']and hashlib.sha256(raw).hexdigest()==sha,'input changed during bounded read')
 return decode(raw),dict(path=str(Path(path).resolve()),**pin)


